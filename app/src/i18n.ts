const messages: Record<Locale, Messages> = { en, zh, ja, ko, de, fr }

export function getInitialLocale(): Locale {
  const saved = localStorage.getItem('wowmd.locale')
  if (saved === 'en' || saved === 'zh' || saved === 'ja' || saved === 'ko' || saved === 'de' || saved === 'fr') {
    return saved
  }
  return navigator.language.toLowerCase().startsWith('zh') ? 'zh' : 'en'
}

export function saveLocale(locale: Locale) {
  localStorage.setItem('wowmd.locale', locale)
}

export function createTranslator(locale: Locale) {
  return (key: string) => messages[locale][key] || messages.en[key] || key
}
